"""Run every gold MetricFlow query and write its result to results/gold/<id>.csv.

Each query goes through the Dex engine (`dex explore semantic query --local`): MetricFlow
renders the SQL from the semantic layer and Dex executes it read-only against the DuckDB
warehouse. A query that fails, or whose result Dex truncated, stops the export.

Usage: uv run python scripts/export_gold.py
"""

import csv
import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "semantic" / "gold_queries.yml"
OUT = ROOT / "results" / "gold"


def run_query(query: dict, where: str | None) -> dict:
    argv = ["dex", "explore", "semantic", "query", ",".join(query["metrics"]), "--local"]
    if query.get("group_by"):
        argv.append("--group-by=" + ",".join(query["group_by"]))
    if where:
        argv.append("--where=" + where)
    if query.get("order_by"):
        argv.append("--order-by=" + ",".join(query["order_by"]))
    proc = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True, check=False)
    lines = proc.stdout.strip().splitlines()
    if not lines:
        sys.exit(f"{query['id']}: dex printed nothing\n{proc.stderr}")
    envelope = json.loads(lines[-1])
    if envelope["status"] != "ok":
        sys.exit(f"{query['id']}: {envelope['status']} ({envelope.get('reason')}): {envelope.get('errors')}")
    data = envelope["data"]
    if data.get("truncated"):
        sys.exit(f"{query['id']}: result was truncated at {data.get('row_count')} rows")
    return data


def write_index(rows: list[dict]) -> None:
    lines = [
        "# Gold query results",
        "",
        "Generated by `make gold` from [`semantic/gold_queries.yml`](../../semantic/gold_queries.yml).",
        "Each CSV is the output of one governed MetricFlow query, run through the Dex engine against",
        "`warehouse/pace_the_frontier.duckdb`. Do not edit these files by hand; change the semantic",
        "layer or the manifest and re-run `make gold`.",
        "",
        "| File | Viz slot | Rows | Question | Metrics | Grouped by | Filter |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        q = row["query"]
        lines.append(
            f"| [`{q['id']}.csv`]({q['id']}.csv) | {q.get('viz', '')} | {row['row_count']} "
            f"| {q['question']} | {', '.join(f'`{m}`' for m in q['metrics'])} "
            f"| {', '.join(f'`{g}`' for g in q.get('group_by', []))} "
            f"| {' + '.join('`' + w + '`' for w in (q.get('where_chunks') or [q.get('where')]) if w)} |"
        )
    (OUT / "README.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    queries = yaml.safe_load(MANIFEST.read_text())["queries"]
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    for query in queries:
        filters = query.get("where_chunks") or [query.get("where")]
        chunks = [run_query(query, where) for where in filters]
        columns = chunks[0]["columns"]
        if any(chunk["columns"] != columns for chunk in chunks):
            sys.exit(f"{query['id']}: chunks returned different columns")
        cells = [row for chunk in chunks for row in chunk["cells"]]
        # Day-grain time columns come back as midnight timestamps; write them as plain dates.
        day_columns = [i for i, name in enumerate(columns) if name.endswith("__day")]
        for row in cells:
            for i in day_columns:
                if isinstance(row[i], str) and row[i].endswith("T00:00:00"):
                    row[i] = row[i][: -len("T00:00:00")]
        with (OUT / f"{query['id']}.csv").open("w", newline="") as handle:
            writer = csv.writer(handle, lineterminator="\n")
            writer.writerow(columns)
            writer.writerows(cells)
        written.append({"query": query, "row_count": len(cells)})
        print(f"{query['id']}: {len(cells)} rows")
    write_index(written)


if __name__ == "__main__":
    main()
